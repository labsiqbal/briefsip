import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium } from '../ui-smoke/node_modules/playwright-core/index.mjs';

const [scratch, phase = 'after'] = process.argv.slice(2);
assert(['before', 'after'].includes(phase), 'Use before or after');
const { origin } = JSON.parse(await readFile(`${scratch}/fixture.out`, 'utf8'));
const output = new URL(`../ui-smoke/artifacts/ux-r5-chat/${phase}/`, import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.setDefaultTimeout(12000);
const results = {}, errors = [];
let newURL;
page.on('pageerror', error => errors.push(error.message));
const post = async (path, data) => { const r = await page.request.post(origin + path, { headers: { Origin: origin }, data }); assert(r.ok(), await r.text()); return r.json(); };
const shot = name => page.screenshot({ path: new URL(`${name}.png`, output).pathname, animations: 'disabled' });
const verify = (value, message) => { results[message] = value; if (phase === 'after') assert(value, message); };
try {
  const agents = [];
  for (const name of ['Iris', 'Theo']) agents.push(await post('/api/agents', { runtime: 'api', id: randomUUID(), name: `R5 ${name} ${phase} ${randomUUID().slice(0, 4)}`, model: 'audit-model', instructions: 'Synthetic fixture.' }));
  const agent = agents[1], path = `/api/agents/${agent.id}/turns`;
  const conversation = await post(`/api/agents/${agent.id}/threads`, { id: randomUUID(), name: 'Launch email' });
  await page.goto(origin);
  const open = async item => { await page.getByRole('tab', { name: /^Agents/ }).click(); await page.getByRole('navigation', { name: 'Choose agent', exact: true }).getByRole('button', { name: new RegExp(`^${item.name}`) }).click(); };
  await open(agent);
  await page.locator(`[data-conversation-id="${conversation.id}"] > .panel-row`).click();
  await page.getByRole('main', { name: 'Conversation Launch email', exact: true }).waitFor();
  await shot('01-before-reload');
  await page.reload();
  await page.waitForTimeout(1200);
  verify(await page.getByRole('main', { name: 'Conversation Launch email', exact: true }).isVisible(), 'conversation restored on reload');
  await shot('01-after-reload');
  await open(agent);
  await page.locator('[data-conversation-id="main"] > .panel-row').click();
  const box = page.getByRole('textbox', { name: `Message ${agent.name}`, exact: true });
  await box.waitFor();
  for (let index = 0; index < 6; index++) await post(path, { id: randomUUID(), text: `Markdown sample ${index}` });
  await page.waitForFunction(async path => (await fetch(path).then(r => r.json())).filter(t => t.status === 'done').length === 6, path, { timeout: 60000 });
  await open(agents[0]); await open(agent); await box.waitFor();
  await page.waitForFunction(() => document.querySelectorAll('.turn-block .reply-answer').length === 6 && document.querySelectorAll('.queued-run').length === 0);
  results.clsRuns = [];
  for (let index = 0; index < 4; index++) {
    if (index) { await open(agents[0]); await open(agent); await box.waitFor(); }
    await page.evaluate(() => {
      window.r5shifts = [];
      window.r5observer?.disconnect();
      window.r5observer = new PerformanceObserver(list => { for (const entry of list.getEntries()) window.r5shifts.push({ value: entry.value, recent: entry.hadRecentInput, sources: entry.sources?.map(source => ({ node: source.node?.className, before: source.previousRect.toJSON(), after: source.currentRect.toJSON() })) }); });
      window.r5observer.observe({ type: 'layout-shift' });
    });
    const text = `Markdown again please ${index}`;
    await box.fill(text); await box.press('Enter');
    await page.waitForTimeout(2200);
    if (!index) await shot('02-sending');
    results.layoutShifts = await page.evaluate(() => window.r5shifts);
    results.clsRuns.push(results.layoutShifts.filter(entry => !entry.recent).reduce((sum, entry) => sum + entry.value, 0));
    await page.waitForFunction(async ({ path, text }) => (await fetch(path).then(r => r.json())).some(t => t.text === text && t.status === 'done'), { path, text });
  }
  results.cls = Math.max(...results.clsRuns);
  verify(results.cls < 0.05, 'cold send CLS below 0.05');
  await page.waitForTimeout(1500);
  const snapshotText = 'Please delay admission snapshot';
  const snapshotStart = Date.now(), snapshotURL = url => url.pathname === path;
  let snapshots = 0;
  await page.route(snapshotURL, async route => {
    if (route.request().method() !== 'GET') return route.continue();
    const response = await route.fetch(), rows = await response.json();
    if (rows.some(turn => turn.text === snapshotText) && Date.now() - snapshotStart < 1800) snapshots++;
    await route.fulfill({ response, json: rows.map(turn => turn.text === snapshotText && Date.now() - snapshotStart < 1800 ? { ...turn, status: 'queued', reply: null, partial: null, activity: { calls: [], tools: [], fallback_model: null } } : turn) });
  });
  await page.route(origin + path.replace('/turns', '/dispatch'), route => Date.now() - snapshotStart < 1800 ? route.fulfill({ json: [] }) : route.continue());
  await page.evaluate(() => { window.r5shifts = []; });
  await box.fill(snapshotText); await box.press('Enter');
  await page.waitForTimeout(1100);
  verify(await page.locator('.turn-block').getByText(snapshotText, { exact: true }).isVisible(), 'queued admission snapshot keeps message in transcript');
  await shot('02-dispatch-snapshot');
  await page.waitForTimeout(1600);
  assert(snapshots > 0, 'Admission snapshot interception reached UI poll');
  results.snapshotShifts = await page.evaluate(() => window.r5shifts);
  results.snapshotCLS = results.snapshotShifts.filter(entry => !entry.recent).reduce((sum, entry) => sum + entry.value, 0);
  verify(results.snapshotCLS < 0.02, 'dispatch snapshot CLS below 0.02');
  await page.unroute(snapshotURL);
  await page.unroute(origin + path.replace('/turns', '/dispatch'));
  await page.waitForFunction(async path => (await fetch(path).then(r => r.json())).every(t => !['queued', 'running'].includes(t.status)), path);
  await box.fill('long slow UXA stream'); await box.press('Enter');
  await page.getByLabel('Streaming answer', { exact: true }).getByText('Synthetic active reply.', { exact: true }).waitFor();
  await box.fill('Please delay queued reply'); await box.press('Enter');
  await page.waitForTimeout(3300);
  await page.locator('.composer').getByRole('button', { name: 'Stop', exact: true }).click();
  await page.getByRole('button', { name: /^Stopped after/ }).waitFor();
  await page.waitForTimeout(600);
  const running = page.locator('.turn-block').last();
  const working = await running.getByRole('button', { name: /^Working/ }).innerText();
  results.queuedTimer = working;
  verify(!/Working… [3-9]s/.test(working), 'queued timer starts at execution');
  const stopped = page.locator('.turn-block').filter({ hasText: 'long slow UXA stream' });
  verify(await stopped.getByRole('button', { name: 'Fork from here', exact: true }).count() === 1 && await stopped.locator('.turn-controls time').count() === 1, 'stopped reply has Fork and time');
  await stopped.hover(); await shot('03-stopped-and-queue');
  await page.waitForFunction(async path => (await fetch(path).then(r => r.json())).every(t => !['queued', 'running'].includes(t.status)), path);
  const rail = page.getByTestId('timeline-minimap');
  results.minimap = await rail.count() ? await rail.evaluate(node => { const tick = node.querySelector('.timeline-minimap__tick').getBoundingClientRect(); const col = document.querySelector('.transcript__col').getBoundingClientRect(); return { visible: !!node.getClientRects().length, gap: col.left - tick.right }; }) : { visible: false };
  verify(!results.minimap.visible || results.minimap.gap >= 16, 'minimap keeps 16px text gap');
  await shot('04-minimap');
  await page.getByRole('button', { name: 'New conversation', exact: true }).click();
  await page.waitForTimeout(500);
  verify(await page.getByRole('dialog', { name: 'New conversation', exact: true }).count() === 0, 'new conversation opens immediately');
  await shot('05-new-conversation');
  if (phase === 'after') {
    assert.equal(await box.evaluate(el => el === document.activeElement), true);
    newURL = page.url();
    await box.fill('Plan launch'); await box.press('Enter');
    await page.getByRole('main', { name: 'Conversation Plan launch', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Menu conversation Plan launch', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Rename', exact: true }).click();
    const rename = page.getByRole('textbox', { name: 'Conversation name', exact: true });
    await rename.fill(''); await rename.press('Enter');
    await page.getByText('Enter a conversation name.', { exact: true }).waitFor();
    assert.equal(await rename.evaluate(el => el.validationMessage), '');
    await shot('05-rename-error');
    await rename.fill('Launch draft'); await shot('05-inline-rename'); await rename.press('Enter');
    await page.getByRole('main', { name: 'Conversation Launch draft', exact: true }).waitFor();
    await shot('05-renamed');
    await open(agents[0]);
    await page.goBack();
    await page.getByRole('main', { name: 'Conversation Launch draft', exact: true }).waitFor();
    await page.goForward();
    await page.getByRole('main', { name: `Conversation ${agents[0].name}`, exact: true }).waitFor();
    await page.goto(newURL);
    await page.getByRole('main', { name: 'Conversation Launch draft', exact: true }).waitFor();
    await page.reload();
    await page.getByRole('main', { name: 'Conversation Launch draft', exact: true }).waitFor();
    results.historyAndUpdate = true;
  } else await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  const project = await post('/api/projects', { id: randomUUID(), name: `R5 Project ${phase} ${randomUUID().slice(0, 4)}`, folders: [], members: agents.map(a => ({ agent: a.id, write: false })) });
  await page.reload();
  await page.getByRole('tab', { name: /^Projects/ }).click();
  await page.getByRole('button', { name: project.name, exact: true }).click();
  if (phase === 'after') { const url = page.url(); await page.reload(); await page.getByRole('heading', { name: project.name, exact: true }).waitFor(); assert.equal(page.url(), url);
    await post(`/api/projects/${project.id}/thread`, { id: randomUUID(), revision: project.revision, agent: agent.id, folder: '', name: 'Project plan' });
    await page.reload();
    await page.getByRole('button', { name: /Project plan/ }).click();
    await page.getByRole('main', { name: 'Conversation Project plan', exact: true }).waitFor();
    await page.reload(); await page.getByRole('main', { name: 'Conversation Project plan', exact: true }).waitFor();
    await page.getByRole('tab', { name: /^Projects/ }).click();
    results.projectConversationRestore = true; }
  await page.getByRole('button', { name: new RegExp(`^# general in ${project.name}`) }).click();
  const roomBox = page.getByRole('textbox', { name: 'Message #general', exact: true });
  await roomBox.fill('Quick round'); await roomBox.press('Enter');
  await page.waitForTimeout(5000);
  const room = page.locator('.room-agent').first();
  await room.hover();
  verify(await room.getByRole('group', { name: 'Message actions', exact: true }).count() === 1 && await room.getByRole('button', { name: 'Fork from here', exact: true }).count() === 1, 'room reply shares direct actions');
  await shot('06-room-actions');
  if (phase === 'after') {
    await page.reload(); await roomBox.waitFor();
    await page.getByRole('button', { name: /^Settings/ }).click();
    await page.getByRole('button', { name: 'Appearance', exact: true }).click();
    await page.reload(); await page.getByRole('dialog', { name: 'Settings', exact: true }).waitFor();
    assert.match(page.url(), /\/settings\/appearance/);
    await page.getByRole('button', { name: 'Close settings', exact: true }).click();
    await roomBox.waitFor();
    await shot('07-restored-room');
    for (const path of [`/agents/${randomUUID()}`, `/agents/${agent.id}/conversations/${randomUUID()}`, `/projects/${randomUUID()}`, `/rooms/${randomUUID()}`, '/agents/deleted', `/agents/${agent.id}/conversations/deleted`, '/projects/deleted', '/rooms/deleted']) {
      await page.goto(origin + path); await page.getByRole('textbox', { name: /^Message / }).waitFor();
      await page.waitForTimeout(300); assert(!page.url().endsWith(path), path);
    }
    await page.goto(newURL);
    await page.getByRole('main', { name: 'Conversation Launch draft', exact: true }).waitFor();
    const deleted = await page.request.get(origin + `/api/threads/${newURL.split('/').at(-1)}`).then(r => r.json());
    await post(`/api/threads/${deleted.id}/delete`, { id: randomUUID(), revision: deleted.revision });
    await page.reload(); await page.getByRole('main', { name: `Conversation ${agent.name}`, exact: true }).waitFor();
    await page.waitForFunction(() => !location.pathname.includes('/conversations/'));
    let releaseCreate, enteredCreate;
    const heldCreate = new Promise(resolve => { releaseCreate = resolve; });
    const createStarted = new Promise(resolve => { enteredCreate = resolve; });
    await page.route(origin + `/api/agents/${agent.id}/threads`, async route => {
      if (route.request().method() !== 'POST') return route.continue();
      const response = await route.fetch(); enteredCreate(); await heldCreate; await route.fulfill({ response });
    });
    await page.getByRole('button', { name: 'New conversation', exact: true }).click();
    await createStarted; await open(agents[0]); releaseCreate(); await page.waitForTimeout(700);
    assert.equal(new URL(page.url()).pathname, `/agents/${agents[0].id}`);
    results.creationDoesNotHijackNavigation = true;
    await page.unroute(origin + `/api/agents/${agent.id}/threads`);
    const createPath = origin + `/api/agents/${agents[0].id}/threads`;
    let saved;
    await page.route(createPath, async route => {
      if (route.request().method() !== 'POST') return route.continue();
      const response = await route.fetch(); saved = await response.json(); await route.abort('failed');
    });
    await page.getByRole('button', { name: 'New conversation', exact: true }).click();
    await page.getByText('Conversation change is not confirmed', { exact: true }).waitFor();
    await page.unroute(createPath); await page.reload();
    await page.getByText('Conversation change is not confirmed', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Retry change', exact: true }).click();
    await page.waitForURL(origin + `/agents/${agents[0].id}/conversations/${saved.id}`);
    await page.getByRole('main', { name: 'Conversation New conversation', exact: true }).waitFor();
    assert.equal((await page.request.get(createPath).then(r => r.json())).filter(thread => thread.id === saved.id).length, 1);
    results.uncertainCreateRecoversAfterReload = true;
    results.safeFallbacks = true;
    assert.deepEqual(errors, []);
  }
} catch (error) { results.error = error.stack; await shot('failure'); throw error; }
finally { await writeFile(new URL('results.json', output), JSON.stringify({ results, errors }, null, 2) + '\n'); await browser.close(); console.log(JSON.stringify(results, null, 2)); }
