import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium } from '../ui-smoke/node_modules/playwright-core/index.mjs';

const [scratch, phase = 'after'] = process.argv.slice(2);
assert(['before', 'after'].includes(phase), 'Use before or after');
const { origin } = JSON.parse(await readFile(`${scratch}/fixture.out`, 'utf8'));
const output = new URL(`../ui-smoke/artifacts/ux-r4-chat/${phase}/`, import.meta.url); await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.setDefaultTimeout(12000);
const errors = [], results = {}, suffix = randomUUID().slice(0, 4);
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
const post = async (path, data) => { const response = await page.request.post(origin + path, { headers: { Origin: origin }, data }); assert(response.ok(), await response.text()); return response.json(); };
const get = path => page.request.get(origin + path).then(response => response.json());
const shot = name => page.screenshot({ path: new URL(`${name}.png`, output).pathname });
const verify = (value, message) => { results[message] = !!value; if (phase === 'after') assert(value, message); };
const settled = path => page.waitForFunction(async path => (await fetch(path).then(response => response.json())).every(turn => !['queued', 'running'].includes(turn.status)), path);
try {
  const agents = [];
  for (const name of ['Iris', 'Theo', 'Mara']) agents.push(await post('/api/agents', { runtime: 'api', id: randomUUID(), name: `${name} R4 ${phase} ${suffix}`, model: 'audit-model', instructions: 'Synthetic only.' }));
  const agent = agents[0], path = `/api/agents/${agent.id}/turns`;
  await page.goto(origin);
  const openAgent = async () => { await page.getByRole('tab', { name: /^Agents/ }).click(); await page.getByRole('navigation', { name: 'Choose agent', exact: true }).getByRole('button', { name: new RegExp(`^${agent.name}`) }).click(); };
  await openAgent();
  const box = page.getByRole('textbox', { name: `Message ${agent.name}`, exact: true });
  const send = async text => { await box.fill(text); await box.press('Enter'); };
  const stop = page.locator('.composer').getByRole('button', { name: 'Stop', exact: true });
  await send('long slow UXA stream');
  await page.getByLabel('Streaming answer', { exact: true }).getByText('Synthetic active reply.', { exact: true }).waitFor();
  await shot('01-streaming'); await stop.click();
  await page.getByRole('button', { name: /^Stopped after/ }).waitFor();
  verify(await page.getByText('Synthetic active reply.', { exact: true }).isVisible(), 'stopped reply remains visible');
  await shot('01-stopped'); await page.reload(); await openAgent();
  await page.getByRole('button', { name: /^Stopped after/ }).waitFor();
  verify(await page.getByText('Synthetic active reply.', { exact: true }).isVisible(), 'stopped reply survives reload');
  await send('long slow UXA stream'); await stop.waitFor();
  await send('Original queue');
  const queue = page.getByRole('region', { name: 'Queued messages', exact: true });
  await queue.getByRole('button', { name: 'Edit', exact: true }).click();
  const edit = queue.getByRole('textbox', { name: 'Replacement message', exact: true });
  await edit.fill('Edited by Enter'); await edit.press('Shift+Enter'); await edit.press('x');
  verify((await edit.inputValue()).includes('\nx'), 'Shift+Enter adds newline');
  await edit.fill('Edited by Enter'); await edit.press('Enter');
  await page.waitForTimeout(300);
  verify(!await edit.isVisible(), 'Enter saves queued edit'); await shot('02-enter-save');
  if (await edit.isVisible()) await queue.getByRole('button', { name: 'Save message', exact: true }).click();
  await queue.getByText('Edited by Enter', { exact: true }).waitFor();
  await queue.getByRole('button', { name: 'Edit', exact: true }).click();
  await edit.fill('Edited across reload'); await shot('02-reload-draft');
  await page.reload(); await openAgent(); await stop.waitFor();
  await page.waitForTimeout(500);
  verify((await get(path)).some(turn => turn.text === 'Edited across reload'), 'reload saves queued draft');
  await shot('02-reloaded');
  const queued = (await get(path)).find(turn => turn.status === 'queued');
  await queue.getByRole('button', { name: 'Edit', exact: true }).click();
  await edit.fill('Edited on blur'); await box.click();
  if (phase === 'after') await queue.getByText('Edited on blur', { exact: true }).waitFor();
  else if (await edit.isVisible()) await queue.getByRole('button', { name: 'Save message', exact: true }).click();
  await queue.getByRole('button', { name: 'Send now', exact: true }).click();
  await settled(path);
  verify((await get(path)).find(turn => turn.id === queued.id)?.text === 'Edited on blur', 'send uses saved edit');
  const stopped = page.locator('.turn-block').filter({ hasText: 'long slow UXA stream' }).last();
  verify(await stopped.getByText('Synthetic active reply.', { exact: true }).isVisible(), 'Send now keeps interrupted reply');
  verify(!await page.getByText(/Restarted from interrupted turn/).isVisible(), 'restart jargon absent'); await shot('03-send-now');
  await send('Please delay reply'); await page.waitForTimeout(2200);
  verify(!await page.getByText('Waiting for provider response...', { exact: true }).isVisible(), 'waiting caption absent');
  const workTurn = page.locator('.turn-block').last();
  const dividerWidth = () => workTurn.evaluate(row => { const header = row.querySelector('.turn-activity__header') ?? row.querySelector('.turn-activity .k-collapsible__trigger'); return header.getBoundingClientRect().width; });
  const runningWidth = await dividerWidth();
  const working = workTurn.getByRole('button', { name: /^Working/ });
  verify(/Working… [2-3]s/.test(await working.innerText()), 'working timer starts at send'); await shot('04-delayed'); await settled(path); await workTurn.getByRole('button', { name: /^Worked/ }).waitFor();
  verify(Math.abs(runningWidth - await dividerWidth()) < 1, 'working divider keeps finished width');
  await send('Use tool'); await settled(path);
  const toolTurn = page.locator('.turn-block').last(); await toolTurn.getByRole('button', { name: /^Worked/ }).click();
  verify(!await toolTurn.getByText('Generated notes.txt', { exact: true }).isVisible(), 'one work log entry per tool');
  verify(await toolTurn.evaluate(row => { const file = row.querySelector('[aria-label="Agent output files"]'), actions = row.querySelector('[aria-label="Message actions"]'); return !!file && !!actions && !!(file.compareDocumentPosition(actions) & Node.DOCUMENT_POSITION_FOLLOWING); }), 'output chips before actions');
  await shot('05-work-log');
  await toolTurn.getByRole('button', { name: 'Fork from here', exact: true }).click();
  const fork = page.getByLabel('Fork origin', { exact: true }); await fork.waitFor();
  verify((await fork.innerText()).includes('Forked from Main chat'), 'fork names source conversation'); await shot('06-fork');
  const project = await post('/api/projects', { id: randomUUID(), name: `R4 ${phase} ${suffix}`, folders: [], members: agents.map(agent => ({ agent: agent.id, write: false })) });
  await page.reload(); await page.getByRole('tab', { name: /^Projects/ }).click();
  await page.getByRole('button', { name: project.name, exact: true }).click();
  await shot('07-project-home');
  verify(await page.locator('.k-section__head').filter({ hasText: 'Folders' }).getByRole('button', { name: 'Add folder', exact: true }).count() === 1, 'Folders header has add action');
  verify(await page.locator('.k-section__head').filter({ hasText: 'Conversations' }).getByRole('button', { name: 'New conversation', exact: true }).count() === 1, 'Conversations header has action');
  const roomLink = page.getByRole('button', { name: new RegExp(`^# general in ${project.name}`) });
  await roomLink.click();
  const roomBox = page.getByRole('textbox', { name: 'Message #general', exact: true });
  await roomBox.fill('Quick round: next steps'); await roomBox.press('Enter');
  const roomPath = `/api/channels/${project.channel}/turns`;
  await page.waitForFunction(async path => (await fetch(path).then(response => response.json())).some(turn => turn.status === 'running' && turn.activity?.calls.length && !turn.partial?.text), roomPath);
  await stop.click(); await settled(roomPath); await page.waitForTimeout(500);
  const started = (await get(roomPath)).filter(turn => turn.status === 'cancelled' && (turn.activity?.calls.length || turn.partial?.text));
  verify(started.length > 0 && started.some(turn => !turn.partial?.text) && await page.locator('.room-agent').filter({ hasText: 'Stopped' }).count() === started.length, 'stopped room speakers remain visible'); await shot('08-stopped-room');
  if (phase === 'after') {
    await roomBox.fill('long slow UXA stream'); await roomBox.press('Enter');
    const partial = page.locator('.room-agent').getByText('Synthetic active reply.', { exact: true });
    await partial.first().waitFor(); await stop.click(); await settled(roomPath);
    verify(await partial.first().isVisible(), 'stopped room partial remains visible'); await shot('08-stopped-room-partial');
    await page.reload(); await page.getByRole('tab', { name: /^Projects/ }).click();
    await roomLink.click();
    await partial.first().waitFor();
    verify(await partial.first().isVisible(), 'stopped room partial survives reload');
  }
  const show = page.getByRole('button', { name: 'Show details', exact: true }); if (await show.isVisible()) await show.click();
  await page.getByRole('tab', { name: 'Activity', exact: true }).click(); await page.waitForTimeout(700);
  verify(await page.getByRole('list', { name: 'Recent runs', exact: true }).count() === 0, 'Activity does not duplicate transcript'); await shot('09-activity');
  await page.getByRole('button', { name: 'New project', exact: true }).last().click();
  const dialog = page.getByRole('dialog', { name: 'New project', exact: true }); await dialog.waitFor();
  const allAgents = (await get('/api/agents')).agents;
  for (const member of allAgents) { await dialog.getByRole('combobox', { name: 'Add project member', exact: true }).click(); await page.getByRole('option', { name: member.name, exact: true }).first().click(); }
  verify(await dialog.getByRole('combobox', { name: 'Add project member', exact: true }).count() === 0, 'all-added member control hidden');
  verify(await dialog.locator('.lucide-trash-2').count() === 0, 'member removal uses X'); await shot('10-project-members');
  if (phase === 'after') assert.deepEqual(errors, []);
} catch (error) { results.error = error.stack; await shot('failure'); throw error; }
finally { await writeFile(new URL('results.json', output), JSON.stringify({ results, errors }, null, 2) + '\n'); await browser.close(); console.log(JSON.stringify(results, null, 2)); }
