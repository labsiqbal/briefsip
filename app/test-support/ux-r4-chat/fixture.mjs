import { createServer } from 'node:http';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { startApp } from '../../test-bridge.ts';

const scratch = process.argv[2];
if (!scratch) throw new Error('Scratch directory required');
await mkdir(scratch, { recursive: true });
const provider = createServer(async (request, response) => {
  let raw = ''; for await (const chunk of request) raw += chunk;
  const json = value => { response.setHeader('Content-Type', 'application/json'); response.end(JSON.stringify(value)); };
  if (request.url === '/v1/models') return json({ data: [{ id: 'audit-model' }] });
  const body = JSON.parse(raw), messages = body.messages;
  const text = String(messages.findLast(message => message.role === 'user')?.content ?? '');
  const room = messages[0]?.content.includes('Group chat.');
  const tool = /tool/i.test(text) && !messages.some(message => message.role === 'tool');
  const answer = text === 'long slow UXA stream' ? 'Synthetic active reply.' : /tool/i.test(text) ? tool ? 'Saving file.' : 'Saved **notes.txt**.' : 'Synthetic reply.';
  response.writeHead(200, { 'Content-Type': 'text/event-stream' });
  const emit = (delta, finish_reason = null) => response.write(`data: ${JSON.stringify({ choices: [{ index: 0, delta, finish_reason }] })}\n\n`);
  if (room || /delay/i.test(text)) await Promise.race([delay(room ? 3000 : 4000), new Promise(resolve => response.once('close', resolve))]);
  if (response.destroyed) return;
  emit({ content: answer });
  if (text === 'long slow UXA stream') await new Promise(resolve => response.once('close', resolve));
  if (response.destroyed) return;
  if (tool) emit({ tool_calls: [{ index: 0, id: 'r4-file', type: 'function', function: { name: 'create_text_file', arguments: JSON.stringify({ name: 'notes.txt', text: 'Synthetic notes.' }) } }] });
  emit({}, tool ? 'tool_calls' : 'stop'); response.end('data: [DONE]\n\n');
});
await new Promise(resolve => provider.listen(0, '127.0.0.1', resolve));
const app = await startApp({ database: join(scratch, 'app.sqlite'), baseURL: `http://127.0.0.1:${provider.address().port}/v1`, defaultModel: 'audit-model', stream: true, projectRoot: join(scratch, 'projects') });
await writeFile(join(scratch, 'fixture.out'), JSON.stringify({ origin: app.origin, pid: process.pid }));
console.log(app.origin);
const stop = async () => { await app.close(); provider.closeAllConnections(); provider.close(); };
process.once('SIGTERM', stop); process.once('SIGINT', stop);
